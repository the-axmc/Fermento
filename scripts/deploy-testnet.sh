#!/usr/bin/env bash
# Deploy the three Fermento contracts to testnet and wire them together.
#
# Usage:
#   scripts/deploy-testnet.sh <admin-key-name>
#
# <admin-key-name> is a Stellar CLI identity (`stellar keys ls`) funded on
# testnet. It becomes admin, pauser, upgrader, minter, issuer, curator and
# treasury. Split the roles later with `grant_role` / `revoke_role`.
#
# Writes deploy/testnet.env with every address the app and scripts need.
# Requires stellar-cli >= 25.2 (soroban-sdk 28).

set -euo pipefail

ADMIN="${1:?usage: scripts/deploy-testnet.sh <admin-key-name>}"
NETWORK="${NETWORK:-testnet}"
# Circle's testnet USDC. Override with USDC_ASSET=CODE:ISSUER if it changes.
USDC_ASSET="${USDC_ASSET:-USDC:GBBD47IF6LWK7P7MDEVSCWR7DPUWV3NY3DTQEVFL4NAT4AQH3ZLLFLA5}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/deploy/testnet.env"
WASM="$ROOT/target/wasm32v1-none/release"
mkdir -p "$ROOT/deploy"

ADMIN_PK="$(stellar keys public-key "$ADMIN")"
echo "admin: $ADMIN_PK"

echo "== build"
(cd "$ROOT" && stellar contract build)
for w in non_fungible_contract batch_shares_contract condition_oracle_contract; do
  stellar contract optimize --wasm "$WASM/$w.wasm" >/dev/null
done

echo "== USDC SAC"
USDC_ID="$(stellar contract id asset --asset "$USDC_ASSET" --network "$NETWORK")"
echo "usdc: $USDC_ID"

echo "== batch registry"
REGISTRY_ID="$(stellar contract deploy \
  --wasm "$WASM/non_fungible_contract.optimized.wasm" \
  --source "$ADMIN" --network "$NETWORK" --alias batch_registry \
  -- --admin "$ADMIN_PK" --pauser "$ADMIN_PK" --upgrader "$ADMIN_PK" --minter "$ADMIN_PK")"
echo "registry: $REGISTRY_ID"

echo "== condition oracle"
ORACLE_ID="$(stellar contract deploy \
  --wasm "$WASM/condition_oracle_contract.optimized.wasm" \
  --source "$ADMIN" --network "$NETWORK" --alias condition_oracle \
  -- --admin "$ADMIN_PK" --curator "$ADMIN_PK")"
echo "oracle: $ORACLE_ID"

echo "== batch shares"
SHARES_ID="$(stellar contract deploy \
  --wasm "$WASM/batch_shares_contract.optimized.wasm" \
  --source "$ADMIN" --network "$NETWORK" --alias batch_shares \
  -- --admin "$ADMIN_PK" --issuer "$ADMIN_PK" --pauser "$ADMIN_PK" \
     --payment_token "$USDC_ID" --registry "$REGISTRY_ID" --treasury "$ADMIN_PK")"
echo "shares: $SHARES_ID"

echo "== let batch_shares record claims on the registry"
stellar contract invoke --id "$REGISTRY_ID" --source "$ADMIN" --network "$NETWORK" \
  -- grant_role --account "$SHARES_ID" --role redeemer --caller "$ADMIN_PK" >/dev/null

cat > "$OUT" <<EOF
# Generated by scripts/deploy-testnet.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
NETWORK=$NETWORK
ADMIN_PK=$ADMIN_PK
USDC_ASSET=$USDC_ASSET
USDC_ID=$USDC_ID
REGISTRY_ID=$REGISTRY_ID
ORACLE_ID=$ORACLE_ID
SHARES_ID=$SHARES_ID
EOF

echo
echo "wrote $OUT"

echo "== inspector role (INSPECTOR=<address> to name an independent one)"
"$(dirname "$0")/grant-inspector.sh" "$ADMIN" "${INSPECTOR:-$ADMIN_PK}"

echo "next: scripts/open-batch.sh $ADMIN 14 moscatel   # register one batch end to end"
